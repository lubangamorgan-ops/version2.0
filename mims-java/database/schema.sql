CREATE TABLE IF NOT EXISTS crops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    unit VARCHAR(255) NOT NULL,
    CONSTRAINT uq_crops_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS markets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    location VARCHAR(255) NOT NULL,
    CONSTRAINT uq_markets_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(16) NOT NULL,
    reset_token_hash VARCHAR(64),
    reset_token_expires_at TIMESTAMP,
    CONSTRAINT uq_accounts_username UNIQUE (username),
    CONSTRAINT uq_accounts_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS farmers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(255),
    profile_image BLOB,
    profile_image_content_type VARCHAR(32),
    market_id BIGINT,
    account_id BIGINT UNIQUE,
    registered_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_farmers_market
        FOREIGN KEY (market_id) REFERENCES markets (id),
    CONSTRAINT fk_farmers_account
        FOREIGN KEY (account_id) REFERENCES accounts (id)
);

CREATE TABLE IF NOT EXISTS price_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_id BIGINT NOT NULL,
    market_id BIGINT NOT NULL,
    price DECIMAL(12, 2) NOT NULL,
    price_date DATE NOT NULL,
    entered_by VARCHAR(255) NOT NULL,
    recorded_at TIMESTAMP NOT NULL,
    revised BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_price_records_crop
        FOREIGN KEY (crop_id) REFERENCES crops (id),
    CONSTRAINT fk_price_records_market
        FOREIGN KEY (market_id) REFERENCES markets (id),
    CONSTRAINT uq_price_records_crop_market_date
        UNIQUE (crop_id, market_id, price_date)
);

CREATE TABLE IF NOT EXISTS broadcasts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sent_at TIMESTAMP NOT NULL,
    sent_by VARCHAR(255) NOT NULL,
    record_count INTEGER NOT NULL,
    recipient_count INTEGER NOT NULL,
    summary VARCHAR(1000)
);

CREATE TABLE IF NOT EXISTS broadcast_price_records (
    broadcast_id BIGINT NOT NULL,
    price_record_id BIGINT NOT NULL,
    CONSTRAINT pk_broadcast_price_records
        PRIMARY KEY (broadcast_id, price_record_id),
    CONSTRAINT fk_broadcast_price_records_broadcast
        FOREIGN KEY (broadcast_id) REFERENCES broadcasts (id),
    CONSTRAINT fk_broadcast_price_records_price_record
        FOREIGN KEY (price_record_id) REFERENCES price_records (id)
);
